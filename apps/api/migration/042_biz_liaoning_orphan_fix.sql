-- ============================================================================
-- 042_biz_liaoning_orphan_fix —— 修复 041 在「辽宁省已存在但 id 不同」环境下的孤儿地市
--
-- 问题：041 用固定 province_id('...031') 插入 14 个辽宁地市。生产库里「辽宁省」是页面
--       手工创建的（id 为 AUTO-…），041 的省份 INSERT 因 code 已存在被跳过，导致这 14 个
--       地市的 province_id 指向一个不存在的省份（孤儿），其中 4 个还与既有地市重名。
-- 修复：① 删除与既有地市重名的 4 条（保留页面早已创建、可能被业务引用的那条）
--       ② 其余 10 条改挂到真实存在的「辽宁省」（按 province code 定位，不写死 id）
--       ③ 清理可能残留的空省份 ...031
-- 说明：在 041 自建省份的全新库里，以上三步都是空操作；可重复执行。
-- ============================================================================

SET NAMES utf8mb4;

-- ① 删除重名的孤儿地市
DELETE c FROM biz_cities c
JOIN biz_cities keep ON keep.name = c.name AND keep.id <> c.id
JOIN biz_provinces p ON p.id = keep.province_id AND p.code = '210000'
LEFT JOIN biz_provinces cp ON cp.id = c.province_id
WHERE cp.id IS NULL
  AND c.id IN ('00000000-0000-4000-8000-000000000240','00000000-0000-4000-8000-000000000241','00000000-0000-4000-8000-000000000242','00000000-0000-4000-8000-000000000243','00000000-0000-4000-8000-000000000244','00000000-0000-4000-8000-000000000245','00000000-0000-4000-8000-000000000246','00000000-0000-4000-8000-000000000247','00000000-0000-4000-8000-000000000248','00000000-0000-4000-8000-000000000249','00000000-0000-4000-8000-000000000250','00000000-0000-4000-8000-000000000251','00000000-0000-4000-8000-000000000252','00000000-0000-4000-8000-000000000253');

-- ② 其余孤儿地市挂到真实的辽宁省
UPDATE biz_cities c
JOIN biz_provinces p ON p.code = '210000'
LEFT JOIN biz_provinces cp ON cp.id = c.province_id
SET c.province_id = p.id
WHERE cp.id IS NULL
  AND c.id IN ('00000000-0000-4000-8000-000000000240','00000000-0000-4000-8000-000000000241','00000000-0000-4000-8000-000000000242','00000000-0000-4000-8000-000000000243','00000000-0000-4000-8000-000000000244','00000000-0000-4000-8000-000000000245','00000000-0000-4000-8000-000000000246','00000000-0000-4000-8000-000000000247','00000000-0000-4000-8000-000000000248','00000000-0000-4000-8000-000000000249','00000000-0000-4000-8000-000000000250','00000000-0000-4000-8000-000000000251','00000000-0000-4000-8000-000000000252','00000000-0000-4000-8000-000000000253');

-- ③ 清理没有地市的空省份（041 自建的 ...031 若已被搬空）
DELETE p FROM biz_provinces p
LEFT JOIN biz_cities c ON c.province_id = p.id
WHERE p.id = '00000000-0000-4000-8000-000000000031'
  AND c.id IS NULL;
